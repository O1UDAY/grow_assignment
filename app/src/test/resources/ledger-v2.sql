CREATE UNIQUE INDEX index_Credit_reference ON Credit(reference);
CREATE UNIQUE INDEX index_Credit_eventKey ON Credit(eventKey);
CREATE TABLE Allocation (id TEXT NOT NULL PRIMARY KEY, credit TEXT NOT NULL, due TEXT NOT NULL, amount INTEGER NOT NULL, reason TEXT NOT NULL);
CREATE TABLE ActivityLine (id INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, text TEXT NOT NULL);
CREATE TABLE Draft (id TEXT NOT NULL PRIMARY KEY, message TEXT NOT NULL);
CREATE TABLE SeenInput (token TEXT NOT NULL PRIMARY KEY);
